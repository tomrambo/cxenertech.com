export const messages = { th, en } as const

type MessageNode = string | { readonly [key: string]: MessageNode }

export function translate(locale: LocaleCode, key: string): string {
  const parts = key.split('.')
  let node: MessageNode = messages[locale] as MessageNode
  for (const part of parts) {
    if (typeof node === 'string' || node == null || !(part in node)) return key
    node = node[part]
  }
  return typeof node === 'string' ? node : key
}
